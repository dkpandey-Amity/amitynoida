export function doubleHyphenMatcher(segments: UrlSegment[]) {
  if (
    segments.length >= 2 &&
    segments.some((segment) => segment.path.includes('--'))
  ) {
    return {
      consumed: segments,
    };
  }

  return null;
}

export function oldListUrlMatcher(segments: UrlSegment[]) {
  if (
    segments.length === 3 &&
    ['ug', 'pg'].includes(segments[0].path) &&
    !isNaN(Number(segments[2].path))
  ) {
    return {
      consumed: segments,
      posParams: {
        Disciplineslugname: segments[1],
        id: segments[2],
      },
    };
  }

  return null;
}

export function oldDetailsUrlMatcher(segments: UrlSegment[]) {
  if (
    segments.length === 4 &&
    ['ug', 'pg', 'phd'].includes(segments[0].path) &&
    !isNaN(Number(segments[3].path))
  ) {
    return {
      consumed: segments,
      posParams: {
        Disciplineslugname: segments[1],
        SlugName: segments[2],
        id: segments[3],
      },
    };
  }

  return null;
}

export function oldSimpleDetailsMatcher(segments: UrlSegment[]) {
  const allowedPaths = [
    'industry-ug-programs',
    'ug-3-continent',
    'ug-international-programmes',
    'integrated-programs',
    'ug-evening-program',
    'pg-industry-program',
    'pg-3-continent',
    'pg-international-programmes',
    'pg-integrated-programmes',
    'pg-evening-program',
  ];

  if (
    segments.length === 3 &&
    allowedPaths.includes(segments[0].path) &&
    !isNaN(Number(segments[2].path))
  ) {
    return {
      consumed: segments,
      posParams: {
        SlugName: segments[1],
        id: segments[2],
      },
    };
  }

  return null;
}

